function makeSamples(
  ttftMs: number,
  thinkingMs: number,
  genMs: number,
  reasoningTokens: number,
  outputTokens: number,
  baseTps: number
): TokenTimingSample[] {
  const samples: TokenTimingSample[] = [];
  const totalSteps = 12;
  const rSteps = reasoningTokens > 0 ? 4 : 0;
  const cSteps = totalSteps - rSteps;

  for (let i = 1; i <= rSteps; i += 1) {
    const ratio = i / rSteps;
    const elapsedMs = Math.round(ttftMs + thinkingMs * ratio);
    const cum = Math.round(reasoningTokens * ratio);
    const wave = 1 + Math.sin(i * 1.4) * 0.08;
    samples.push({
      elapsedMs,
      cumulativeTokens: cum,
      instantTps: Number((baseTps * 0.92 * wave).toFixed(1)),
      phase: 'reasoning',
    });
  }

  for (let j = 1; j <= cSteps; j += 1) {
    const ratio = j / cSteps;
    const elapsedMs = Math.round(ttftMs + thinkingMs + genMs * ratio);
    const cum = reasoningTokens + Math.round(outputTokens * ratio);
    const wave = 1 + Math.cos(j * 1.1) * 0.09;
    samples.push({
      elapsedMs,
      cumulativeTokens: cum,
      instantTps: Number((baseTps * wave).toFixed(1)),
      phase: 'content',
    });
  }

  return samples;
}

